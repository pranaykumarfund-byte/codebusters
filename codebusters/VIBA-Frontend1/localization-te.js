function applyTextNode(node) {
  const current = node.nodeValue;
  if (current === null) return;
  let remembered = textNodeState.get(node);
  if (!remembered || current !== remembered.rendered) remembered = { original: current, rendered: current };
  const next = translateExact(remembered.original, activeLanguage);
  if (next !== current) node.nodeValue = next;
  remembered.rendered = next;
  textNodeState.set(node, remembered);
}

function translateAttribute(element, attribute) {
  if (!element.hasAttribute(attribute)) return;
  const originalKey = `data-viba-original-${attribute}`;
  let original = element.getAttribute(originalKey);
  const current = element.getAttribute(attribute) || '';
  if (original === null) {
    original = current;
    element.setAttribute(originalKey, original);
  } else if (current !== translateExact(original, 'te') && current !== original) {
    original = current;
    element.setAttribute(originalKey, original);
  }
  const next = translateExact(original, activeLanguage);
  if (current !== next) element.setAttribute(attribute, next);
}

function localizeElement(element) {
  if (!(element instanceof Element)) return;
  for (const candidate of [element, ...element.querySelectorAll('*')]) {
    for (const attribute of ['aria-label', 'title', 'placeholder', 'alt']) translateAttribute(candidate, attribute);
  }
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue?.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || parent.closest('script,style,textarea,[contenteditable="true"],.language-button,.ai-chat-message.user')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(applyTextNode);
}

export function localizeUi(root = document.body, language = 'en') {
  activeLanguage = language === 'te' ? 'te' : 'en';
  if (root instanceof Text) applyTextNode(root);
  else if (root instanceof Element) localizeElement(root);
  if (!observer && document.body) {
    observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') applyTextNode(mutation.target);
        for (const node of mutation.addedNodes || []) {
          if (node.nodeType === Node.TEXT_NODE) applyTextNode(node);
          else if (node instanceof Element) localizeElement(node);
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
}
